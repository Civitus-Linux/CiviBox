#include <ncurses.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../etc/commands.c"

#define CONFIG_FILE ".config"
#define MAX_COMMANDS 256

enum {
    MENU_MAIN,
    MENU_COMPILE,
    MENU_COMMANDS,
    MENU_EXTRA
};

struct config {
    int compile_static;
    int commands[MAX_COMMANDS];
    int extra[MAX_COMMANDS];
};

static struct config cfg;

static const char *const *command_lists[] = {
    command_list,
    extracommand_list
};

static int *config_lists[] = {
    cfg.commands,
    cfg.extra
};

static const char *menu_names[] = {
    "Commands",
    "Commands (Extra)"
};

static int command_count(int menu)
{
    int count = 0;

    while (count < MAX_COMMANDS &&
           command_lists[menu][count])
        count++;

    return count;
}

static void config_name(char *buf, size_t size,
                        const char *command, int extra)
{
    const char *prefix = extra ? "CONFIG_EXTRA_" : "CONFIG_";
    size_t i = 0;

    while (*prefix && i + 1 < size)
        buf[i++] = *prefix++;

    while (*command && i + 1 < size) {
        char c = *command++;

        if (c >= 'a' && c <= 'z')
            c -= 32;

        buf[i++] = c;
    }

    buf[i] = '\0';
}

static void load_config(void)
{
    FILE *file = fopen(CONFIG_FILE, "r");

    if (!file) {
        cfg.compile_static = 1;

        for (int m = 0; m < 2; m++)
            for (int i = 0; i < command_count(m); i++)
                config_lists[m][i] = 1;

        return;
    }

    char line[256];

    while (fgets(line, sizeof(line), file)) {
        if (!strncmp(line, "CONFIG_COMPILE_STATIC=y", 23)) {
            cfg.compile_static = 1;
            continue;
        }

        for (int m = 0; m < 2; m++) {
            int count = command_count(m);

            for (int i = 0; i < count; i++) {
                char name[160];
                char value[180];

                config_name(name, sizeof(name),
                            command_lists[m][i], m == 1);

                snprintf(value, sizeof(value), "%s=y", name);

                if (!strncmp(line, value, strlen(value))) {
                    config_lists[m][i] = 1;
                    break;
                }

                snprintf(value, sizeof(value),
                         "# %s is not set", name);

                if (!strncmp(line, value, strlen(value))) {
                    config_lists[m][i] = 0;
                    break;
                }
            }
        }
    }

    fclose(file);
}

static void save_config(void)
{
    FILE *file = fopen(CONFIG_FILE, "w");

    if (!file)
        return;

    fprintf(file,
        "#\n"
        "# CiviBox configuration\n"
        "# Automatically generated by menuconfig\n"
        "#\n\n");

    fprintf(file, "CONFIG_COMPILE_STATIC=%c\n\n",
            cfg.compile_static ? 'y' : 'n');

    for (int m = 0; m < 2; m++) {
        int count = command_count(m);

        for (int i = 0; i < count; i++) {
            char name[160];

            config_name(name, sizeof(name),
                        command_lists[m][i], m == 1);

            if (config_lists[m][i])
                fprintf(file, "%s=y\n", name);
            else
                fprintf(file, "# %s is not set\n", name);
        }

        fprintf(file, "\n");
    }

    fclose(file);
}

static void header(const char *title)
{
    attron(COLOR_PAIR(1) | A_BOLD);
    mvhline(0, 0, ' ', COLS);
    mvprintw(0, (COLS - (int)strlen(title)) / 2, "%s", title);
    attroff(COLOR_PAIR(1) | A_BOLD);
}

static void footer(void)
{
    attron(COLOR_PAIR(1));
    mvhline(LINES - 2, 0, ' ', COLS);
    mvhline(LINES - 1, 0, ' ', COLS);

    mvprintw(LINES - 2, 2,
             "<Enter> Select  <Space> Toggle  <Esc> Back");

    mvprintw(LINES - 1, 2,
             "<S> Save  <Q> Quit");

    attroff(COLOR_PAIR(1));
}

static void item(int row, int selected, const char *text)
{
    attron(selected ? COLOR_PAIR(2) | A_BOLD : COLOR_PAIR(1));

    mvhline(row, 0, ' ', COLS);
    mvprintw(row, 3, "%s", text);

    attroff(selected ? COLOR_PAIR(2) | A_BOLD : COLOR_PAIR(1));
}

static void compile_menu(void)
{
    int running = 1;

    while (running) {
        erase();
        header("Compile settings");

        char text[128];

        snprintf(text, sizeof(text), "[%c] COMPILE_STATIC",
                 cfg.compile_static ? '*' : ' ');

        item(3, 1, text);
        footer();
        refresh();

        switch (getch()) {
        case ' ':
            cfg.compile_static = !cfg.compile_static;
            break;
        case 's':
        case 'S':
            save_config();
            break;
        case 27:
        case 'q':
        case 'Q':
            running = 0;
            break;
        }
    }
}

static void commands_menu(int menu)
{
    int selected = 0;
    int running = 1;
    int count = command_count(menu);

    if (!count)
        return;

    while (running) {
        erase();
        header(menu_names[menu]);

        int visible = LINES - 7;

        if (visible < 1)
            visible = 1;

        int start = selected >= visible
                  ? selected - visible + 1 : 0;

        for (int i = 0; i < visible && start + i < count; i++) {
            int index = start + i;
            char text[160];

            snprintf(text, sizeof(text), "[%c] %s",
                     config_lists[menu][index] ? '*' : ' ',
                     command_lists[menu][index]);

            item(3 + i, selected == index, text);
        }

        footer();
        refresh();

        switch (getch()) {
        case KEY_UP:
            if (selected > 0)
                selected--;
            break;

        case KEY_DOWN:
            if (selected < count - 1)
                selected++;
            break;

        case KEY_NPAGE:
            selected += visible;
            if (selected >= count)
                selected = count - 1;
            break;

        case KEY_PPAGE:
            selected -= visible;
            if (selected < 0)
                selected = 0;
            break;

        case KEY_HOME:
            selected = 0;
            break;

        case KEY_END:
            selected = count - 1;
            break;

        case ' ':
            config_lists[menu][selected] =
                !config_lists[menu][selected];
            break;

        case 's':
        case 'S':
            save_config();
            break;

        case 27:
        case 'q':
        case 'Q':
            running = 0;
            break;
        }
    }
}

static void main_menu(void)
{
    const char *items[] = {
        "Compile settings  --->",
        "Commands          --->",
        "Commands (Extra)  --->"
    };

    int selected = 0;
    int running = 1;

    while (running) {
        erase();
        header("CiviBox Configuration");

        for (int i = 0; i < 3; i++)
            item(3 + i, selected == i, items[i]);

        footer();
        refresh();

        switch (getch()) {
        case KEY_UP:
            if (selected > 0)
                selected--;
            break;

        case KEY_DOWN:
            if (selected < 2)
                selected++;
            break;

        case '\n':
        case KEY_ENTER:
            if (selected == 0)
                compile_menu();
            else
                commands_menu(selected - 1);
            break;

        case 's':
        case 'S':
            save_config();
            break;

        case 27:
        case 'q':
        case 'Q':
            running = 0;
            break;
        }
    }
}

int main(void)
{
    load_config();

    initscr();

    if (has_colors()) {
        start_color();
        init_pair(1, COLOR_WHITE, COLOR_BLUE);
        init_pair(2, COLOR_BLUE, COLOR_WHITE);
        bkgd(COLOR_PAIR(1));
    }

    cbreak();
    noecho();
    keypad(stdscr, TRUE);
    curs_set(0);

    main_menu();

    endwin();

    return 0;
}
